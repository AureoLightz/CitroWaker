#!/usr/bin/env python3
"""Original mathematical cloth for the fallback panel. No external art/input."""
import argparse
import math
from pathlib import Path

def pixels():
    for x in range(320):
        for y in range(239, -1, -1):
            h = ((x * 73856093) ^ (y * 19349663) ^ 0x57414B45) & 0xFFFFFFFF
            h = ((h ^ (h >> 13)) * 1274126177) & 0xFFFFFFFF
            noise = ((h & 255) / 255 - .5) * 2
            weave = 1.5 * math.sin(x * math.pi / 2) * math.sin(y * math.pi / 2)
            light = 1 + 1.5 * math.cos((x - 130) / 220) * math.cos((y - 65) / 180)
            r, g, b = (max(0, min(255, int(v + noise + weave + light))) for v in (23, 34, 46))
            yield ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    values = list(pixels())
    assert len(values) == 320 * 240
    text = '#pragma once\n#include <cstdint>\n// Original procedural cloth, generated by presentation/original_cloth/generate.py.\n// No disc artwork, fonts, symbols or sampled textures.\nalignas(4) static const uint16_t kBottomUiTexture[320*240]={\n'
    text += ''.join(','.join(hex(v) for v in values[i:i+16]) + ',\n' for i in range(0, len(values), 16)) + '};\n'
    args.output.write_text(text)

if __name__ == '__main__':
    main()
